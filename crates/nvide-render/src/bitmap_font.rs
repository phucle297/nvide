//! Tiny 8×8 monospaced bitmap font for Phase 0 GPU text prototype.

/// Glyph cell size in atlas pixels.
pub const GLYPH_PX: u32 = 8;

/// Atlas is 16 columns × 16 rows of 8×8 glyphs → covers full u8 code points.
pub const ATLAS_COLS: u32 = 16;
pub const ATLAS_ROWS: u32 = 16;
pub const ATLAS_WIDTH: u32 = ATLAS_COLS * GLYPH_PX;
pub const ATLAS_HEIGHT: u32 = ATLAS_ROWS * GLYPH_PX;

/// Build an R8 atlas (255 = ink). Printable ASCII uses a 5×7 pattern; others a box.
pub fn build_atlas_r8() -> Vec<u8> {
    let mut pixels = vec![0u8; (ATLAS_WIDTH * ATLAS_HEIGHT) as usize];
    for code in 0u32..256 {
        let bits = glyph_bits(code as u8);
        let col = code % ATLAS_COLS;
        let row = code / ATLAS_COLS;
        let ox = col * GLYPH_PX;
        let oy = row * GLYPH_PX;
        for y in 0..8u32 {
            let row_bits = bits[y as usize];
            for x in 0..8u32 {
                let on = (row_bits >> (7 - x)) & 1 == 1;
                let idx = ((oy + y) * ATLAS_WIDTH + (ox + x)) as usize;
                pixels[idx] = if on { 255 } else { 0 };
            }
        }
    }
    pixels
}

/// UV rectangle for `ch` in the atlas (normalized 0–1).
pub fn glyph_uv(ch: char) -> (f32, f32, f32, f32) {
    let code = if (ch as u32) <= 255 {
        ch as u32
    } else {
        b'?' as u32
    };
    let col = (code % ATLAS_COLS) as f32;
    let row = (code / ATLAS_COLS) as f32;
    let u0 = col * GLYPH_PX as f32 / ATLAS_WIDTH as f32;
    let v0 = row * GLYPH_PX as f32 / ATLAS_HEIGHT as f32;
    let u1 = (col + 1.0) * GLYPH_PX as f32 / ATLAS_WIDTH as f32;
    let v1 = (row + 1.0) * GLYPH_PX as f32 / ATLAS_HEIGHT as f32;
    (u0, v0, u1, v1)
}

fn glyph_bits(code: u8) -> [u8; 8] {
    if code == b' ' {
        return [0; 8];
    }
    if let Some(rows) = pattern_for(code) {
        return pack_5x7(&rows);
    }
    // Hollow box fallback
    [
        0b01111110, 0b01000010, 0b01000010, 0b01000010, 0b01000010, 0b01000010, 0b01111110, 0,
    ]
}

fn pack_5x7(rows: &[&str; 7]) -> [u8; 8] {
    let mut out = [0u8; 8];
    for (y, row) in rows.iter().enumerate() {
        // Center patterns shorter than 5 columns.
        let chars: Vec<char> = row.chars().collect();
        let width = chars.len().min(5);
        let pad = (5 - width) / 2;
        let mut bits = 0u8;
        for (i, ch) in chars.iter().take(5).enumerate() {
            if *ch == '#' {
                // bit 6 is leftmost ink column (1-pixel left margin)
                bits |= 1 << (6 - (i + pad).min(4));
            }
        }
        out[y + 1] = bits;
    }
    out
}

