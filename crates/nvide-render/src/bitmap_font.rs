#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn atlas_has_ink_for_letters() {
        let a = build_atlas_r8();
        assert_eq!(a.len(), (ATLAS_WIDTH * ATLAS_HEIGHT) as usize);
        for ch in ['H', 'i', 'G', 'l', 'y', 'p', 'h', 's'] {
            let code = ch as u32;
            let col = code % ATLAS_COLS;
            let row = code / ATLAS_COLS;
            let mut ink = 0u32;
            for y in 0..8 {
                for x in 0..8 {
                    let idx = ((row * GLYPH_PX + y) * ATLAS_WIDTH + (col * GLYPH_PX + x)) as usize;
                    if a[idx] > 0 {
                        ink += 1;
                    }
                }
            }
            assert!(ink > 3, "expected ink for {ch:?}, got {ink}");
        }
    }
}
